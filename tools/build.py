#!/usr/bin/env python3
"""Generuje statyczne strony bohaterek z podglądem Open Graph.

GitHub Pages nie ma serwera, a roboty Facebooka/Messengera nie wykonują JavaScriptu,
więc metadane muszą być w HTML-u. Dla każdej bohaterki z config.js powstają:

  <slug>.html        – kopia index.html z tagami og:* (serwowana pod /<slug>, status 200)
  og/<slug>.jpg      – obraz podglądu 1200×630 (zdjęcie bez rozciągania na rozmytym tle)

index.html dostaje tagi domyślnej bohaterki (invite.defaultSlug). Skrypt podbija też
numery wersji plików (?v=...) na podstawie ich zawartości.

Użycie (z katalogu repozytorium):  python3 tools/build.py
Wymaga: python3, Pillow, node.
"""
import hashlib
import html
import json
import os
import re
import subprocess
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageEnhance

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

W, H = 1200, 630
MARK = "<!-- generated by tools/build.py -->"
OG_RE = re.compile(r"<!-- og:start -->.*?<!-- og:end -->", re.S)


def load_config():
    out = subprocess.check_output(
        ["node", "-e", "global.window={};require('./config.js');console.log(JSON.stringify(window.SITE_CONFIG))"],
        text=True,
    )
    return json.loads(out)


def domain():
    with open("CNAME") as f:
        return f.read().strip()


def make_og_image(src, dst):
    """1200×630: rozmyte, przyciemnione tło z tego samego zdjęcia + ostry portret w całości."""
    im = Image.open(src).convert("RGB")
    sw, sh = im.size

    # tło: zdjęcie dopasowane „cover” do 1200×630 (proporcjonalnie), kadr z górą zdjęcia
    scale = W / sw
    bg = im.resize((W, round(sh * scale)), Image.LANCZOS)
    top = int((bg.height - H) * 0.18)
    bg = bg.crop((0, top, W, top + H)).filter(ImageFilter.GaussianBlur(38))
    bg = ImageEnhance.Brightness(bg).enhance(0.5)

    # pierwszy plan: całe zdjęcie w pełnej wysokości, bez rozciągania
    fw = round(sw * H / sh)
    fg = im.resize((fw, H), Image.LANCZOS)
    mask = Image.new("L", (fw, H), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, fw - 1, H - 1), radius=0, fill=255)
    bg.paste(fg, ((W - fw) // 2, 0), mask)

    os.makedirs(os.path.dirname(dst), exist_ok=True)
    bg.save(dst, "JPEG", quality=84, optimize=True, progressive=True)


def og_block(cfg, p, host, page=None):
    og = cfg.get("og", {})
    fill = lambda t: t.replace("{imie}", p["name"]).replace("{wiek}", str(p["age"]))
    title = fill(og.get("title", "{imie} zaprasza Cię do dołączenia do znajomych"))
    desc = fill(og.get("description", "{imie}, {wiek} lat, przesłała Ci zaproszenie."))
    page = page or f"https://{host}/{p['slug']}"
    image = f"https://{host}/og/{p['slug']}.jpg"
    alt = f"{p['name']}, {p['age']} – zdjęcie profilowe"
    e = lambda v: html.escape(v, quote=True)
    site = e(og.get("siteName", host))
    return "\n".join([
        "<!-- og:start -->",
        f"<title>{e(title)} | {site}</title>",
        f'<meta name="description" content="{e(desc)}" />',
        f'<link rel="canonical" href="{e(page)}" />',
        '<meta property="og:type" content="website" />',
        f'<meta property="og:site_name" content="{site}" />',
        '<meta property="og:locale" content="pl_PL" />',
        f'<meta property="og:url" content="{e(page)}" />',
        f'<meta property="og:title" content="{e(title)}" />',
        f'<meta property="og:description" content="{e(desc)}" />',
        f'<meta property="og:image" content="{e(image)}" />',
        f'<meta property="og:image:secure_url" content="{e(image)}" />',
        '<meta property="og:image:type" content="image/jpeg" />',
        f'<meta property="og:image:width" content="{W}" />',
        f'<meta property="og:image:height" content="{H}" />',
        f'<meta property="og:image:alt" content="{e(alt)}" />',
        '<meta name="twitter:card" content="summary_large_image" />',
        f'<meta name="twitter:title" content="{e(title)}" />',
        f'<meta name="twitter:description" content="{e(desc)}" />',
        f'<meta name="twitter:image" content="{e(image)}" />',
        "<!-- og:end -->",
    ])


def file_hash(path):
    with open(path, "rb") as f:
        return hashlib.sha1(f.read()).hexdigest()[:8]


def main():
    cfg = load_config()
    host = domain()
    profiles = cfg["profiles"]
    default = cfg.get("invite", {}).get("defaultSlug") or profiles[0]["slug"]
    by_slug = {p["slug"]: p for p in profiles}

    # numery wersji z zawartości plików (koniec z ręcznym podbijaniem ?v=)
    ver = {name: file_hash(name) for name in ("style.css", "config.js", "app.js")}

    with open("index.html", encoding="utf-8") as f:
        template = f.read()
    if not OG_RE.search(template):
        sys.exit("index.html: brak znaczników <!-- og:start --> ... <!-- og:end -->")

    def versioned(t):
        for name, v in ver.items():
            t = re.sub(re.escape(name) + r"\?v=[0-9a-z]+", f"{name}?v={v}", t)
        return t

    # index.html: tagi domyślnej bohaterki
    index = OG_RE.sub(lambda m: og_block(cfg, by_slug[default], host, f"https://{host}/"), template)
    index = versioned(index)
    with open("index.html", "w", encoding="utf-8") as f:
        f.write(index)
    template = index  # strony bohaterek powstają z aktualnego index.html

    slugs = set()
    for p in profiles:
        slug = p["slug"]
        if not re.fullmatch(r"[a-z0-9-]+", slug) or slug in ("index", "404", "og", "img", "tools"):
            sys.exit(f"niedozwolony slug: {slug}")
        slugs.add(slug)
        make_og_image(p["photo"], f"og/{slug}.jpg")
        page = OG_RE.sub(lambda m: og_block(cfg, p, host), template)
        page = page.replace("<!doctype html>", "<!doctype html>\n" + MARK, 1)
        with open(f"{slug}.html", "w", encoding="utf-8") as f:
            f.write(page)

    # sprzątanie po usuniętych bohaterkach
    for name in os.listdir("."):
        if name.endswith(".html") and name[:-5] not in slugs and name not in ("index.html", "404.html"):
            with open(name, encoding="utf-8") as f:
                if MARK in f.read(300):
                    os.remove(name)
                    print("usunięto", name)
    if os.path.isdir("og"):
        for name in os.listdir("og"):
            if name.endswith(".jpg") and name[:-4] not in slugs:
                os.remove(os.path.join("og", name))
                print("usunięto og/" + name)

    print(f"OK: {len(slugs)} stron i obrazów OG, domena {host}, wersje {ver}")


if __name__ == "__main__":
    main()
